"""NIYAM's small, allowlisted Windows action layer.

Only fixed actions in this file may be invoked. This module never executes
commands generated by the language model and never accepts arbitrary URLs.
"""

import re
import subprocess
import webbrowser
from datetime import datetime


APPROVED_WEBSITES = {
    "youtube": "https://www.youtube.com/",
}


def handle_local_action(user_text: str) -> str | None:
    """Return an action result, or None when this is normal conversation."""
    text = re.sub(r"\s+", " ", user_text.lower()).strip()
    text = text.strip(" \t\r\n.,!?;:")

    # Accept a few simple polite prefixes without broad intent inference.
    changed = True
    while changed:
        changed = False
        for prefix in ("niyam, ", "niyam ", "please ", "can you ", "could you "):
            if text.startswith(prefix):
                text = text[len(prefix):].strip()
                changed = True
                break

    # Open Notepad using a fixed executable name and no shell.
    if re.fullmatch(r"(?:open|launch|start)(?: the)? notepad", text):
        try:
            subprocess.Popen(["notepad.exe"], shell=False, close_fds=True)
            return "Notepad is opening."
        except OSError:
            return "I couldn't open Notepad. Check that Notepad is available on Windows."

    # Open Calculator using a fixed executable name and no shell.
    if re.fullmatch(r"(?:open|launch|start)(?: the)? calculator", text):
        try:
            subprocess.Popen(["calc.exe"], shell=False, close_fds=True)
            return "Calculator is opening."
        except OSError:
            return "I couldn't open Calculator. Check that Calculator is available on Windows."

    # Current local computer time.
    if text in {
        "what time is it",
        "tell me the time",
        "what is the time",
        "what's the time",
        "current time",
        "tell me the current time",
    }:
        now = datetime.now().astimezone()
        return f"It's {now.strftime('%I:%M %p')} ({now.tzname() or 'local time'})."

    # Open one hard-coded website; do not accept a user-supplied URL.
    if re.fullmatch(r"(?:open|launch|visit)(?: the)? youtube", text):
        try:
            if webbrowser.open_new_tab(APPROVED_WEBSITES["youtube"]):
                return "YouTube is opening in your browser."
            return "I couldn't open the browser automatically."
        except Exception:
            return "Something went wrong while opening YouTube."

    return None
